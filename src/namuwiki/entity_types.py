"""문서를 온톨로지 클래스로 분류한다 (KG-2 타입 계층).

`relations` 가 문서 사이의 관계를 말한다면 여기서는 문서 자체가 **무엇인지**
를 말한다. 김연아는 인물이고, 6.25 전쟁은 사건이고, 토트넘은 조직이다.
타입이 있으면 "축구 선수 중에서" 같은 필터가 가능해지고, 관계의 정합성도
검사할 수 있다 — 사건에 '학력'이 붙어 있으면 추출이 잘못된 것이다.

**클래스는 일곱 개로 닫는다.** 클래스를 늘리면 경계가 흐려져 어느 쪽에도
넣기 애매한 문서가 늘고, 분류기의 정밀도가 떨어진다. 나무위키 분류 체계
(232,870개)를 그대로 옮기는 대신 상위 타입만 둔 이유다.

근거는 두 갈래다. 인포박스 술어가 더 강하다 — '출생'과 '학력'이 함께
있으면 사람이다. 분류 이름은 넓게 걸리지만 노이즈도 많다.

실측 분류 접미사 (상위): 인물 13,234 · 출생 12,366 · 출신 10,961 ·
사고 4,090 · 사건 2,556 · 영화 4,417 · 국가 1,815 · 동물 1,288
"""

from __future__ import annotations

import re

__all__ = ["CLASSES", "classify"]

CLASSES = ("인물", "장소", "조직", "작품", "사건", "생물", "개념")

# 인포박스 술어 → 클래스. 이 술어가 있으면 거의 확실하다.
_PRED_SIGNALS: dict[str, tuple[str, ...]] = {
    "인물": ("출생", "사망", "학력", "배우자", "부모", "자녀", "형제", "국적", "직업"),
    # 셋을 뺐다. '감독'은 영화 감독이자 축구 감독이라 '토트넘 홋스퍼 FC'가
    # 작품이 됐다. '작곡가'는 국가(國歌) 행에 붙어 라트비아·리투아니아를,
    # '장르'는 편성 표에 붙어 JTBC 를 작품으로 만들었다.
    "작품": ("제작사", "배급사", "주연", "출연", "원작"),
    "조직": ("설립자", "창립자", "본사", "회장", "대표", "상위 조직", "산하"),
    "장소": ("수도", "소재지", "정치체제", "통화"),
}
# 여러 클래스의 술어가 섞이면 강한 쪽을 택한다. 장소가 맨 앞인 이유는
# '수도'·'통화'가 사람에게는 절대 붙지 않기 때문이다 — 왕조 문서에는
# 황제의 '사망'이 함께 있어서, 인물을 앞에 두면 당나라가 인물이 된다.
_PRED_ORDER = ("장소", "인물", "조직", "작품")

# 분류 이름에 나타나는 단어 → 클래스. 마지막 단어부터 본다.
_CAT_SIGNALS: dict[str, tuple[str, ...]] = {
    "인물": ("인물", "출생", "출신", "사망", "데뷔", "은퇴", "정치인", "선수",
             "국회의원", "메달리스트", "감독", "배우", "가수", "작가", "군인"),
    "사건": ("사건", "사고", "사건사고", "범죄", "전쟁", "참사", "테러", "재판"),
    "작품": ("영화", "드라마", "게임", "애니메이션", "소설", "만화", "앨범",
             "노래", "프로그램", "웹툰", "뮤지컬"),
    "조직": ("정당", "기업", "설립", "학교", "대학교", "구단", "축구단", "창단",
             "회사", "단체", "방송국", "정부", "부대", "협회", "연맹"),
    "장소": ("국가", "개최국", "도시", "개최도시", "지역", "행정구역", "자치단체", "특별시",
             "광역시", "수도", "소재지", "지명", "산", "강", "섬", "역",
             "공항", "건축물", "도로"),
    "생물": ("동물", "식물", "곤충", "어류", "조류", "포유류", "생물"),
}
# 동점일 때의 우선순위. 작품을 장소·조직보다 뒤에 둔다 — '아시안 게임
# 개최국'(작품 신호)과 '서아시아 국가'(장소 신호)가 동점이면 카타르는
# 장소여야 하고, SBS 는 '보도 프로그램'보다 '양천구의 기업'이 맞다.
# 인물이 맨 뒤인 이유는 '이순신 관련 사건'처럼 인물 이름이 붙은 분류가
# 다른 타입 문서에도 흔하기 때문이다.
_CAT_ORDER = ("사건", "생물", "장소", "조직", "작품", "인물")


# 연도·날짜 문서. 인포박스가 없는데도 문서 안의 목록 표가 '감독'·'장르'
# 같은 술어로 잡혀 '2020년'이 작품으로 분류됐다. 이들은 연대순 색인이다.
_CALENDAR = re.compile(r"^(\d{1,4}년(대)?|\d{1,2}월( \d{1,2}일)?)$")

# 자기 분류는 배열 앞쪽에 온다. 뒤쪽은 둘러보기 틀에서 새어든 것이다 —
# '문화방송' 뒤에는 그 방송사의 드라마·예능 분류가 줄줄이 붙어서, 세면
# 조직이 아니라 작품으로 판정된다. '프랑스어'는 7번째부터 '코트디부아르의
# 인물'이 붙는다. 앞에서 이만큼만 본다.
_OWN_CATEGORIES = 6


def _matches(word: str, keys: tuple[str, ...]) -> bool:
    """완전 일치, 또는 세 글자 이상 키로 끝나는 경우.

    한국어 합성어는 머리명사가 뒤에 온다 — '광역자치단체'는 자치단체의
    일종이므로 접미 일치가 맞다. 아무 위치나 허용하는 부분 일치는 너무
    헐거워서 'SBS'와 '카타르'를 작품으로 만들었다.
    """
    return word in keys or any(
        len(k) >= 3 and word != k and word.endswith(k) for k in keys
    )


def _from_predicates(preds: set[str]) -> str | None:
    for cls in _PRED_ORDER:
        if preds & set(_PRED_SIGNALS.get(cls, ())):
            return cls
    return None


def _from_categories(categories: list[str], title: str = "") -> str | None:
    # 클래스마다 몇 개의 분류가 걸리는지 세고 가장 많이 걸린 쪽을 고른다.
    # 한 단어만 보고 결정하면 '대한민국의 남성 영화 감독'이 작품이 된다.
    score: dict[str, int] = {}
    for cat in categories[:_OWN_CATEGORIES]:
        # '분류:서울특별시 출신 인물' 처럼 접두어가 남은 것은 목차에서
        # 새어 들어온 부산물이다. 서울특별시가 인물로 분류된 원인이었다.
        if cat.startswith("분류:"):
            continue
        # 자기 이름이 들어간 분류는 그 문서가 **무엇인지**가 아니라 그것과
        # 관련된 것들을 모은 목록이다. '경기도 출신 인물'은 경기도가
        # 인물이라는 뜻이 아니고, '2020년 영화'는 2020년이 영화라는 뜻이
        # 아니다. 실제로 둘 다 그렇게 잘못 분류됐다.
        if title and title != cat and title in cat:
            continue
        # 한국어 합성어는 머리명사가 맨 뒤다. 분류가 무엇의 목록인지는
        # 마지막 단어가 정한다 — '아시안 게임 개최국'은 게임이 아니라
        # 개최국이고, 그 구분이 없으면 카타르가 작품이 된다.
        words = cat.replace("의", " ").split()
        if not words:
            continue
        head = words[-1]
        for cls, keys in _CAT_SIGNALS.items():
            if _matches(head, keys):
                score[cls] = score.get(cls, 0) + 1
    if not score:
        return None
    best = max(score.values())
    # 동점이면 고정 순서로 가른다. 인물이 가장 뒤인 이유는 '이순신 관련
    # 사건'처럼 인물 이름이 붙은 사건 분류가 흔하기 때문이다.
    for cls in _CAT_ORDER:
        if score.get(cls) == best:
            return cls
    return None


def classify(categories: list[str], predicates: set[str], title: str = "") -> str:
    """분류와 인포박스 술어로 클래스를 정한다. 확신이 없으면 '개념'."""
    if title and _CALENDAR.match(title):
        return "개념"
    return (
        _from_predicates(predicates)
        or _from_categories(categories or [], title)
        or "개념"
    )
